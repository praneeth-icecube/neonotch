import AppKit
import UniformTypeIdentifiers

enum ClipboardPayload {
    case text(String)
    case image(NSImage)
    case files([URL])
}

struct ClipboardEntry: Identifiable {
    let id: UUID
    let payload: ClipboardPayload
    let capturedAt: Date
    let sourceApp: String?
    let sourceIcon: NSImage?
    let sourceBundleID: String?
    /// Pinned entries sit first, survive "Clear" and never age out.
    var isPinned: Bool

    init(
        id: UUID = UUID(),
        payload: ClipboardPayload,
        capturedAt: Date,
        sourceApp: String?,
        sourceIcon: NSImage?,
        sourceBundleID: String? = nil,
        isPinned: Bool = false
    ) {
        self.id = id
        self.payload = payload
        self.capturedAt = capturedAt
        self.sourceApp = sourceApp
        self.sourceIcon = sourceIcon
        self.sourceBundleID = sourceBundleID
        self.isPinned = isPinned
    }

    var preview: String {
        switch payload {
        case .text(let string):
            let flat = string
                .replacingOccurrences(of: "\n", with: " ")
                .trimmingCharacters(in: .whitespacesAndNewlines)
            return flat.isEmpty ? "(whitespace)" : flat
        case .image:
            return "Image"
        case .files(let urls):
            return urls.count == 1
                ? urls[0].lastPathComponent
                : "\(urls.count) files"
        }
    }

    /// The text itself, for the AI actions. Nil for images and files.
    var text: String? {
        if case .text(let string) = payload { return string }
        return nil
    }

    var symbol: String {
        switch payload {
        case .text(let string):
            if string.hasPrefix("http://") || string.hasPrefix("https://") { return "link" }
            return "text.alignleft"
        case .image: return "photo"
        case .files: return "doc"
        }
    }

    var detail: String {
        switch payload {
        case .text(let string):
            let count = string.count
            return "\(count) character\(count == 1 ? "" : "s")"
        case .image(let image):
            return "\(Int(image.size.width))×\(Int(image.size.height))"
        case .files(let urls):
            guard urls.count == 1 else { return "Files" }
            let ext = urls[0].pathExtension.uppercased()
            return ext.isEmpty ? "File" : ext
        }
    }

    /// Compact age, e.g. "4m ago". `Text(_, style: .relative)` spells this out
    /// as "4 min, 2 sec", which is too noisy for a one-line row.
    var age: String {
        let seconds = Date().timeIntervalSince(capturedAt)
        if seconds < 60 { return "\(max(1, Int(seconds))) sec ago" }
        let formatter = RelativeDateTimeFormatter()
        formatter.unitsStyle = .abbreviated
        return formatter.localizedString(for: capturedAt, relativeTo: Date())
    }
}

/// Watches the general pasteboard and keeps a rolling history.
///
/// Password managers and other privacy-minded apps mark their contents with
/// `org.nspasteboard.ConcealedType`; we honour that and skip those entries, so
/// they are never shown and never written to disk.
///
/// With "Keep history across restarts" on, text and file entries are saved to
/// `clipboard.json`. Images stay in memory only.
final class ClipboardModel: ObservableObject {
    @Published private(set) var entries: [ClipboardEntry] = []
    @Published var searchText = ""

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?
    private let preferences = Preferences.shared
    private static let file = "clipboard.json"

    private static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    init() {
        lastChangeCount = pasteboard.changeCount
        restore()
        start()
    }

    deinit {
        timer?.invalidate()
    }

    /// Pinned first, then newest first, filtered by the search.
    var filteredEntries: [ClipboardEntry] {
        let ordered = entries.filter(\.isPinned) + entries.filter { !$0.isPinned }
        guard !searchText.isEmpty else { return ordered }
        let needle = searchText.lowercased()
        return ordered.filter { $0.preview.lowercased().contains(needle) }
    }

    var hasUnpinned: Bool { entries.contains { !$0.isPinned } }

    func start() {
        guard timer == nil else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { [weak self] _ in
            self?.poll()
        }
        timer?.tolerance = 0.2
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    // MARK: Capture

    private func poll() {
        guard preferences.clipboardEnabled else { return }
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let types = Set(pasteboard.types ?? [])
        if preferences.ignoreConcealedClipboardItems,
           types.contains(Self.concealedType)
            || types.contains(Self.transientType)
            || types.contains(Self.autoGeneratedType) {
            return
        }

        guard let payload = readPayload() else { return }
        let frontmost = NSWorkspace.shared.frontmostApplication
        let entry = ClipboardEntry(
            payload: payload,
            capturedAt: Date(),
            sourceApp: frontmost?.localizedName,
            sourceIcon: frontmost?.icon,
            sourceBundleID: frontmost?.bundleIdentifier
        )

        // Collapse consecutive duplicates so holding ⌘C does not spam history.
        if let first = entries.first, isDuplicate(first, entry) { return }

        Trace.log("clipboard", "captured \(entry.symbol) \"\(entry.preview.prefix(40))\" from \(entry.sourceApp ?? "?")")
        entries.insert(entry, at: 0)
        trimToLimit()
        persist()
    }

    private func readPayload() -> ClipboardPayload? {
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [
            .urlReadingFileURLsOnly: true
        ]) as? [URL], !urls.isEmpty {
            return .files(urls)
        }
        if let string = pasteboard.string(forType: .string),
           !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return .text(string)
        }
        if let images = pasteboard.readObjects(forClasses: [NSImage.self]) as? [NSImage],
           let image = images.first {
            return .image(image)
        }
        return nil
    }

    private func isDuplicate(_ lhs: ClipboardEntry, _ rhs: ClipboardEntry) -> Bool {
        switch (lhs.payload, rhs.payload) {
        case let (.text(a), .text(b)): return a == b
        case let (.files(a), .files(b)): return a == b
        default: return false
        }
    }

    /// The limit applies to unpinned entries; pins never age out.
    private func trimToLimit() {
        var unpinnedSeen = 0
        entries.removeAll { entry in
            guard !entry.isPinned else { return false }
            unpinnedSeen += 1
            return unpinnedSeen > preferences.clipboardHistoryLimit
        }
    }

    // MARK: Actions

    /// Puts an entry back on the pasteboard, ready to paste.
    func copy(_ entry: ClipboardEntry) {
        pasteboard.clearContents()
        switch entry.payload {
        case .text(let string):
            pasteboard.setString(string, forType: .string)
        case .image(let image):
            pasteboard.writeObjects([image])
        case .files(let urls):
            pasteboard.writeObjects(urls as [NSURL])
        }
        // Do not re-capture what we just wrote.
        lastChangeCount = pasteboard.changeCount
    }

    /// Copies new text — an AI result — and records it as the newest entry.
    func copyText(_ text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        lastChangeCount = pasteboard.changeCount
        entries.insert(
            ClipboardEntry(payload: .text(text), capturedAt: Date(), sourceApp: "Apple Intelligence", sourceIcon: nil),
            at: 0
        )
        trimToLimit()
        persist()
    }

    func togglePin(_ entry: ClipboardEntry) {
        guard let index = entries.firstIndex(where: { $0.id == entry.id }) else { return }
        entries[index].isPinned.toggle()
        persist()
    }

    func remove(_ entry: ClipboardEntry) {
        entries.removeAll { $0.id == entry.id }
        persist()
    }

    /// Clears the history, keeping pinned entries.
    func clear() {
        entries.removeAll { !$0.isPinned }
        persist()
    }

    // MARK: Persistence

    private struct StoredEntry: Codable {
        var id: UUID
        var text: String?
        var paths: [String]?
        var capturedAt: Date
        var sourceApp: String?
        var sourceBundleID: String?
        var isPinned: Bool
    }

    private func persist() {
        guard preferences.keepClipboardHistory else {
            try? FileManager.default.removeItem(at: Storage.url(for: Self.file))
            return
        }
        let stored: [StoredEntry] = entries.compactMap { entry in
            switch entry.payload {
            case .text(let text):
                StoredEntry(id: entry.id, text: text, paths: nil, capturedAt: entry.capturedAt,
                            sourceApp: entry.sourceApp, sourceBundleID: entry.sourceBundleID, isPinned: entry.isPinned)
            case .files(let urls):
                StoredEntry(id: entry.id, text: nil, paths: urls.map(\.path), capturedAt: entry.capturedAt,
                            sourceApp: entry.sourceApp, sourceBundleID: entry.sourceBundleID, isPinned: entry.isPinned)
            case .image:
                nil
            }
        }
        Storage.save(stored, to: Self.file)
    }

    private func restore() {
        guard preferences.keepClipboardHistory,
              let stored = Storage.load([StoredEntry].self, from: Self.file)
        else { return }
        entries = stored.compactMap { item in
            let payload: ClipboardPayload
            if let text = item.text {
                payload = .text(text)
            } else if let paths = item.paths, !paths.isEmpty {
                payload = .files(paths.map { URL(fileURLWithPath: $0) })
            } else {
                return nil
            }
            let icon = item.sourceBundleID
                .flatMap { NSWorkspace.shared.urlForApplication(withBundleIdentifier: $0) }
                .map { NSWorkspace.shared.icon(forFile: $0.path) }
            return ClipboardEntry(
                id: item.id,
                payload: payload,
                capturedAt: item.capturedAt,
                sourceApp: item.sourceApp,
                sourceIcon: icon,
                sourceBundleID: item.sourceBundleID,
                isPinned: item.isPinned
            )
        }
    }

    #if DEBUG
    /// Used by `Snapshotter` and SwiftUI previews; stops live capture.
    func debugReplace(_ newEntries: [ClipboardEntry]) {
        stop()
        entries = newEntries
    }
    #endif

    /// A file representation of the entry so it can be dragged out of the panel.
    func itemProvider(for entry: ClipboardEntry) -> NSItemProvider {
        switch entry.payload {
        case .text(let string):
            return NSItemProvider(object: string as NSString)
        case .image(let image):
            return NSItemProvider(object: image)
        case .files(let urls):
            guard let first = urls.first, let provider = NSItemProvider(contentsOf: first) else {
                return NSItemProvider()
            }
            return provider
        }
    }
}
